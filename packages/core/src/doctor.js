import { readdir, readFile, stat } from 'node:fs/promises'
import { join } from 'node:path'
import { fileLockHeld, portOpen } from './lock.js'
import { isSessionFile, isStraySessionsDir } from './scan.js'
import { patchMountsRemovedTool } from './compat.js'
import { inspectZstd, isZstd, readSessionHeader } from './session.js'
import { parseYaml, YamlError } from './yaml.js'

function finding(level, code, path, zh, en) {
  return { level, code, path, zh, en }
}

function bomOf(buf) {
  if (buf.length >= 3 && buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf) return 'utf-8'
  if (buf.length >= 2 && buf[0] === 0xff && buf[1] === 0xfe) return 'utf-16-le'
  if (buf.length >= 2 && buf[0] === 0xfe && buf[1] === 0xff) return 'utf-16-be'
  return null
}

async function walk(root, onEntry, skip) {
  async function rec(abs, rel, depth) {
    if (depth > 12) return
    let st
    try {
      st = await stat(abs)
    } catch {
      return
    }
    if (st.isSymbolicLink()) return
    if (st.isDirectory()) {
      if (rel) await onEntry({ abs, rel, size: 0, dir: true })
      if (skip?.(rel)) return
      let names = []
      try {
        names = await readdir(abs)
      } catch {
        return
      }
      for (const name of names) await rec(join(abs, name), rel ? `${rel}/${name}` : name, depth + 1)
      return
    }
    if (st.isFile()) await onEntry({ abs, rel, size: st.size, dir: false })
  }
  try {
    await rec(root, '', 0)
  } catch {
    /* missing root */
  }
}

/**
 * Read-only health check of a DSH_HOME. Never writes.
 */
export async function doctor(dshHome) {
  const findings = []
  const sessions = []
  let sawNodeModules = false
  let sawProjcache = false
  const textLike = (rel) => /\.(yml|yaml|json|md|txt)$/.test(rel) || rel.endsWith('cordis.patch.yml')

  await walk(dshHome, async (file) => {
    const name = file.rel.split('/').pop()
    if (file.dir) {
      if (isStraySessionsDir(name)) {
        findings.push(finding('error', 'stray_sessions_tilde', file.rel, '发现多余的 sessions~ 目录，导入中断时会留下它，工作区会因此打不开', 'Stray sessions~ directory. An interrupted import leaves these behind and workspace creation fails'))
      }
      return
    }
    if (name === 'cordis.yml' && file.rel.startsWith('profiles/')) {
      findings.push(finding('info', 'cordis_yml_excluded', file.rel, 'cordis.yml 由运行时重新生成，备份不会包含它', 'cordis.yml is regenerated by the runtime and is not part of a backup'))
    }
    if (file.rel === '.credentials.yaml' || name === '.credentials.yaml' || name === '.env') {
      findings.push(finding('info', 'credentials_present', file.rel, '发现凭据文件。默认不备份，专业版可以单独打开', 'Credential file present. Excluded by default; Pro can opt in'))
    }
    if (name.endsWith('.db-wal') || name.endsWith('.sqlite-wal') || name.endsWith('-wal') && file.rel.startsWith('storages/')) {
      findings.push(finding('info', 'sqlite_wal', file.rel, '发现 SQLite WAL。快照会走 backup()，不会按字节复制 WAL', 'SQLite WAL is present. Snapshots use backup(), not a raw copy of the WAL'))
    }
    if (file.rel.startsWith('sessions/') && isSessionFile(name)) sessions.push(file)
    if (!textLike(file.rel) && !file.rel.endsWith('.yml')) return
    if (file.size > 5_000_000) return
    let buf
    try {
      buf = await readFile(file.abs)
    } catch {
      return
    }
    const bom = bomOf(buf)
    if (bom) {
      findings.push(finding('error', 'bom', file.rel, `文件带有 ${bom} BOM，dsh 会拒绝这种补丁或存储`, `File has a ${bom} BOM. dsh rejects patches and storage files that start with one`))
    }
    const body = bom === 'utf-8' ? buf.subarray(3) : buf
    if (name === 'cordis.patch.yml' || name === 'cordis.yml') {
      try {
        const parsed = parseYaml(body.toString('utf8'))
        if (name === 'cordis.patch.yml' && parsed !== null && !Array.isArray(parsed)) {
          findings.push(finding('warn', 'bad_patch_yml', file.rel, 'cordis.patch.yml 不是列表。补丁应该是一组插件行', 'cordis.patch.yml is not a list. A patch should be a sequence of plugin rows'))
        }
        if (name === 'cordis.patch.yml' && patchMountsRemovedTool(body.toString('utf8'))) {
          findings.push(finding(
            'warn',
            'removed_working_directory_tool',
            file.rel,
            '补丁还挂着 tool-working-directory。dsh 0.2.2-rc.3 及以后加载时会拒绝这一项。恢复会删掉这个模型工具，并保留 working-directory 服务。会话事件和 header.cwd 不会改写。',
            'This patch still mounts tool-working-directory. dsh 0.2.2-rc.3 and later refuse that entry at load. Restore drops the model tool and keeps the working-directory service. Session events and header.cwd are not rewritten.',
          ))
        }
      } catch (error) {
        const line = error instanceof YamlError ? error.line : 0
        findings.push(finding('error', 'bad_patch_yml', file.rel, `补丁 YAML 无法解析${line ? `（第 ${line} 行）` : ''}：${error.message}`, `Patch YAML failed to parse${line ? ` (line ${line})` : ''}: ${error.message}`))
      }
    }
    if (file.rel.startsWith('storages/') && name.endsWith('.json') && !file.rel.includes('session_projcache/')) {
      try {
        const json = JSON.parse(body.toString('utf8'))
        if (json && typeof json === 'object' && json.unit && !Number.isInteger(json.unit.version)) {
          findings.push(finding('error', 'bad_version_stamp', file.rel, '存储单元缺少整数版本戳。降级前必须有升级前快照', 'Storage unit is missing an integer version stamp. Downgrade needs a pre-upgrade snapshot'))
        }
      } catch (error) {
        findings.push(finding('error', 'bad_storage_json', file.rel, `存储 JSON 无法解析：${error.message}`, `Storage JSON failed to parse: ${error.message}`))
      }
    }
  }, (rel) => {
    if (!rel) return false
    const base = rel.split('/')[0]
    if (base === 'cache') return true
    if (rel.includes('session_projcache')) {
      if (!sawProjcache) {
        sawProjcache = true
        findings.push(finding('info', 'projcache_excluded', rel, 'session_projcache 是派生缓存，备份会跳过', 'session_projcache is derived cache and is excluded'))
      }
      return true
    }
    if (rel.split('/').includes('node_modules')) {
      if (!sawNodeModules) {
        sawNodeModules = true
        findings.push(finding('info', 'node_modules_excluded', rel, 'node_modules 不备份。恢复时按 lockfile 重装', 'node_modules is not backed up. Restore reinstalls from the lockfile'))
      }
      return true
    }
    return false
  })

  const byDir = new Map()
  for (const file of sessions) {
    const dir = file.rel.split('/').slice(0, -1).join('/')
    const list = byDir.get(dir) ?? []
    list.push(file)
    byDir.set(dir, list)
  }
  const headers = []
  for (const [dir, files] of byDir) {
    const names = new Set(files.map((file) => file.rel.split('/').pop()))
    for (const name of names) {
      if (!name.endsWith('.zstd')) continue
      const plain = name.slice(0, -'.zstd'.length)
      if (names.has(plain)) {
        findings.push(finding('error', 'session_compression_mismatch', dir, '同一会话里同时有 .jsonl 和 .jsonl.zstd。后端压缩模式对不上就会拒绝打开', 'A session directory has both .jsonl and .jsonl.zstd. The backend refuses the compression mismatch'))
      }
    }
    for (const file of files) {
      const buf = await readFile(file.abs)
      if (buf.length === 0) {
        findings.push(finding('error', 'broken_session', file.rel, '会话文件是空的', 'Session file is empty'))
        continue
      }
      if (file.rel.endsWith('.zstd') || isZstd(buf)) {
        const info = inspectZstd(buf)
        if (!info.ok || info.frames.length === 0) {
          findings.push(finding('error', 'broken_session', file.rel, 'zstd 会话无法解压', 'zstd session could not be decompressed'))
        } else if (info.truncated) {
          findings.push(finding('error', 'truncated_session', file.rel, 'zstd 会话尾部被截断。快照会丢掉不完整的最后一帧，源文件不会被修改', 'zstd session tail is truncated. A snapshot drops the incomplete last frame and does not modify the source'))
        }
        const header = readSessionHeader(buf, true)
        if (header) headers.push(header)
        else if (info.ok) findings.push(finding('warn', 'broken_session', file.rel, '会话头不是 JSON', 'Session header is not JSON'))
      } else {
        const text = buf.toString('utf8')
        const lines = text.split('\n').filter((line, index, all) => line.length > 0 || index < all.length - 1)
        let bad = 0
        for (const line of lines) {
          if (!line) continue
          try {
            JSON.parse(line)
          } catch {
            bad += 1
          }
        }
        if (!text.endsWith('\n')) {
          findings.push(finding('warn', 'truncated_session', file.rel, 'jsonl 会话最后一行不完整', 'jsonl session has an incomplete last line'))
        } else if (bad) {
          findings.push(finding('error', 'broken_session', file.rel, 'jsonl 会话里有无法解析的行', 'jsonl session contains a line that is not JSON'))
        }
        const header = readSessionHeader(buf, false)
        if (header) headers.push(header)
      }
    }
  }

  let workspace = null
  let workspaceMissing = false
  try {
    const raw = await readFile(join(dshHome, 'storages', 'workspace.json'))
    try {
      workspace = JSON.parse(raw.toString('utf8').replace(/^\uFEFF/, ''))
    } catch {
      workspace = null
    }
  } catch {
    workspaceMissing = true
  }
  if (sessions.length > 0 && workspaceMissing) {
    findings.push(finding('error', 'missing_workspace_registry', 'storages/workspace.json', '有会话但没有工作区登记。侧边栏会空，创建工作区也会失败', 'Sessions exist but the workspace registry is missing. The sidebar stays empty and workspace create fails'))
  }
  if (workspace && sessions.length > 0) {
    const table = workspace.tables?.workspaces
    const count = table && typeof table === 'object' ? Object.keys(table).length : 0
    const withCwd = headers.filter((header) => typeof header.cwd === 'string' && header.cwd.length > 0)
    if (count === 0 && withCwd.length > 0) {
      findings.push(finding('warn', 'workspace_registry_empty', 'storages/workspace.json', '工作区表是空的，但会话头里有工作目录。这些会话会掉进未分组', 'The workspace table is empty while session headers have a working directory. Those sessions fall into Ungrouped'))
    }
    const known = new Set(headers.map((header) => header.id).filter(Boolean))
    if (table && typeof table === 'object') {
      for (const [id, record] of Object.entries(table)) {
        const ids = Array.isArray(record?.sessionIds) ? record.sessionIds : []
        for (const sessionId of ids) {
          if (!known.has(sessionId)) {
            findings.push(finding('warn', 'workspace_session_missing', `storages/workspace.json#${id}`, `工作区登记了会话 ${sessionId}，但会话文件里没有这个头`, `Workspace record lists session ${sessionId}, but no session header has that id`))
          }
        }
      }
    }
  }

  const locks = []
  await walk(join(dshHome, 'sessions'), async (file) => {
    if (file.rel.endsWith('session.lock') || file.rel.split('/').pop() === 'session.lock') locks.push(file.abs)
  })
  const desktopLock = join(dshHome, 'profiles', 'desktop', 'lock')
  try {
    await stat(desktopLock)
    locks.push(desktopLock)
  } catch {
    /* none */
  }
  for (const file of locks) {
    const held = fileLockHeld(file)
    if (held.held) {
      findings.push(finding('warn', 'dsh_running', file, '锁被占用，dsh 可能正在运行。这种时候不能恢复', 'Lock is held, so dsh may be running. Restore is refused in that state'))
    }
  }
  if (await portOpen(3999)) {
    findings.push(finding('warn', 'dsh_running', '127.0.0.1:3999', '3999 端口开着，桌面端可能在运行', 'Port 3999 is open. The desktop app may be running'))
  }

  const errors = findings.filter((item) => item.level === 'error').length
  const warnings = findings.filter((item) => item.level === 'warn').length
  return { dshHome, findings, errors, warnings, ok: errors === 0 }
}
